-- Zetaris setup for CargoPilot's station evidence. Run each statement on its own,
-- in order, in the Zetaris SQL Editor (one statement per call). Admin rights needed.
-- Replace the <...> placeholders in the editor only; never commit credentials.
-- DESCRIBE BY values: letters, digits, _ . - , only (no spaces), or Zetaris rejects the statement.

-- Source 1: Postgres handling history (see 01_postgres_handling_history.sql)
CREATE DATASOURCE ops_pg DESCRIBE BY "cargopilot_station_handling_history" OPTIONS (
  jdbcdriver "org.postgresql.Driver",
  jdbcurl "jdbc:postgresql://<neon-host>/<database>?sslmode=require",
  username "<read-only user>",
  password "<password>",
  fetchsize "1000"
);

REGISTER DATASOURCE TABLE "handling_history" FROM ops_pg;

-- Source 2: live METAR for the five stations, from the public aviationweather.gov
-- Data API (no key), through scripts/wx-adapter.mjs (a container on the Zetaris
-- network). A REST table's schema is inferred once at CREATE; aviationweather's
-- `wdir` flips between a number and "VRB", which broke every query an hour after
-- creation. The adapter keeps the same GeoJSON layout with string-only fields.
CREATE LIGHTNING DATABASE CARGOWX_REST DESCRIBE BY "aviationweather.gov_metar_live";

CREATE LIGHTNING REST TABLE metar_geojson FROM CARGOWX_REST REQUEST(
    endpoint "http://cargopilot-wx:8787/metar",
    method "get",
    response_type "json",
    http_encoding "URLENCODED"
) HEADER (
) BODY ();

CREATE SCHEMASTORE CONTAINER cargo_wx;

CREATE SCHEMASTORE VIEW metar_now WITH CONTAINER cargo_wx AS
SELECT
    f.properties.id      AS icao,
    f.properties.fltcat  AS fltcat,
    f.properties.obsTime AS obs_time,
    f.properties.rawOb   AS rawob
FROM cargowx_rest.metar_geojson
LATERAL VIEW explode(features) AS f;

-- Checks
SELECT icao, fltcat, rawob FROM cargo_wx.metar_now;
SELECT station, count(*) FROM ops_pg.handling_history GROUP BY station;

-- The federated query CargoPilot sends (generated by zetarisSql() in
-- src/lib/ops/evidence.ts; this is the one for file 615-12345675):
SELECT h.station, h.process, h.flight, h.window_min, h.wx_category,
       COUNT(*) AS n,
       SUM(CASE WHEN h.within_window THEN 1 ELSE 0 END) AS hits,
       percentile_approx(h.actual_min, 0.5) AS p50_min,
       percentile_approx(h.actual_min, 0.9) AS p90_min,
       MAX(h.actual_min) AS max_min,
       MAX(m.fltcat) AS metar_now, MAX(m.rawob) AS metar_raw
FROM ops_pg.handling_history h
LEFT JOIN cargo_wx.metar_now m ON m.icao = h.icao
WHERE h.flight IN ('AYC 552', 'AYC 7841', 'AYC 9864')
GROUP BY h.station, h.process, h.flight, h.window_min, h.wx_category
ORDER BY h.station, h.flight, h.wx_category;
