/**
 * Generates data/ops/handling_history.csv — 90 days of SIMULATED station
 * handling performance for the transfer and acceptance processes CargoPilot's
 * files depend on. Deterministic (seeded), so the file is reproducible:
 *
 *   npx tsx scripts/gen-ops-history.ts
 *
 * Each row is one past movement: how long the process took against the window
 * it had, and the flight category (VFR/MVFR/IFR) at the station when it ran.
 * The weather column is what lets the agent join live TAF data with history
 * ("when LEJ is IFR, how often does the 45 min window hold?").
 *
 * Nothing here comes from a real carrier, handler or shipper.
 */
import { mkdirSync, writeFileSync } from "node:fs";

type Process = {
  station: string;
  icao: string;
  process: string;
  flight: string;
  windowMin: number;
  /** median duration in VFR, minutes */
  p50: number;
  /** log-normal spread */
  sigma: number;
  /** extra median minutes per weather category */
  wxPenalty: Record<Wx, number>;
  perDay: number;
};

type Wx = "VFR" | "MVFR" | "IFR" | "LIFR";

const PROCESSES: Process[] = [
  // s615: road feeder truck into LEJ, 45 min to break down and build up for AYC 7841
  { station: "LEJ", icao: "EDDP", process: "truck_to_flight", flight: "AYC 7841", windowMin: 45, p50: 37, sigma: 0.2, wxPenalty: { VFR: 0, MVFR: 4, IFR: 11, LIFR: 18 }, perDay: 2 },
  // s615 reroute options
  { station: "ZRH", icao: "LSZH", process: "truck_to_flight", flight: "AYC 9864", windowMin: 60, p50: 41, sigma: 0.18, wxPenalty: { VFR: 0, MVFR: 3, IFR: 7, LIFR: 12 }, perDay: 2 },
  { station: "FRA", icao: "EDDF", process: "truck_to_flight", flight: "AYC 552", windowMin: 60, p50: 46, sigma: 0.22, wxPenalty: { VFR: 0, MVFR: 4, IFR: 9, LIFR: 15 }, perDay: 2 },
  // s125: CDG minimum connection time 50 min
  { station: "CDG", icao: "LFPG", process: "flight_connection", flight: "AYC 045", windowMin: 50, p50: 42, sigma: 0.17, wxPenalty: { VFR: 0, MVFR: 3, IFR: 8, LIFR: 14 }, perDay: 1 },
  // GVA export acceptance → ready for carriage (acceptance-close files)
  { station: "GVA", icao: "LSGG", process: "acceptance_to_ready", flight: "AYC 090", windowMin: 40, p50: 29, sigma: 0.2, wxPenalty: { VFR: 0, MVFR: 1, IFR: 3, LIFR: 5 }, perDay: 1 },
  { station: "GVA", icao: "LSGG", process: "acceptance_to_ready", flight: "AYC 880", windowMin: 60, p50: 38, sigma: 0.18, wxPenalty: { VFR: 0, MVFR: 1, IFR: 3, LIFR: 5 }, perDay: 1 },
];

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(20261014);
function normal(): number {
  const u = Math.max(rand(), 1e-12);
  const v = rand();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}
function wxDraw(): Wx {
  const r = rand();
  // Autumn evenings in central Europe: mostly VFR, some fog and low cloud.
  return r < 0.62 ? "VFR" : r < 0.82 ? "MVFR" : r < 0.95 ? "IFR" : "LIFR";
}

const END = Date.UTC(2026, 9, 13); // 13 Oct 2026, the day before the desk clock
const DAYS = 90;
const rows: string[] = ["date,station,icao,process,flight,window_min,actual_min,within_window,wx_category"];
for (let d = DAYS; d >= 1; d--) {
  const date = new Date(END - (d - 1) * 86_400_000).toISOString().slice(0, 10);
  // One weather draw per station per day, shared by its processes.
  const wxByStation = new Map<string, Wx>();
  for (const p of PROCESSES) {
    if (!wxByStation.has(p.station)) wxByStation.set(p.station, wxDraw());
    const wx = wxByStation.get(p.station)!;
    for (let k = 0; k < p.perDay; k++) {
      const median = p.p50 + p.wxPenalty[wx];
      const actual = Math.max(10, Math.round(median * Math.exp(p.sigma * normal())));
      rows.push([date, p.station, p.icao, p.process, p.flight, p.windowMin, actual, actual <= p.windowMin, wx].join(","));
    }
  }
}

mkdirSync("data/ops", { recursive: true });
const csv = rows.join("\n") + "\n";
writeFileSync("data/ops/handling_history.csv", csv);
// Same table as a module, so the app and the offline judge path read it without fs or a network.
writeFileSync(
  "src/lib/ops/history.data.ts",
  "// GENERATED by scripts/gen-ops-history.ts — do not edit. Same rows as data/ops/handling_history.csv.\n" +
    `export const HANDLING_HISTORY_CSV = ${JSON.stringify(csv)};\n`,
);
console.log(`wrote data/ops/handling_history.csv + src/lib/ops/history.data.ts (${rows.length - 1} rows)`);
